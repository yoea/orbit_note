// 随机取一条（排除当前索引，避免点击后原地不动）
export function randomPromptIndex(exclude?: number): number {
  if (PROMPTS.length <= 1) return 0
  let i = Math.floor(Math.random() * PROMPTS.length)
  while (i === exclude) {
    i = Math.floor(Math.random() * PROMPTS.length)
  }
  return i
}

// 上报提示显示次数（尽力而为，失败静默）——prompt_stats 表，后续按频率展示用
export function reportPromptShown(index: number): void {
  void fetch('/api/prompts/record', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ index }),
  }).catch(() => {})
}
