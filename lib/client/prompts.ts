// 剩余池（一轮内不重复，全部展示完重新洗牌）
const POOL_KEY = 'qo-prompt-pool'

function shuffledAll(): number[] {
  const pool = PROMPTS.map((_, i) => i)
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1))
    ;[pool[i], pool[j]] = [pool[j], pool[i]]
  }
  return pool
}

function loadPool(): number[] {
  try {
    const raw = localStorage.getItem(POOL_KEY)
    if (raw) {
      const arr = JSON.parse(raw) as unknown
      if (Array.isArray(arr) && arr.length > 0 && arr.every((n) => typeof n === 'number' && Number.isInteger(n) && n >= 0 && n < PROMPTS.length)) {
        return arr
      }
    }
  } catch { /* 池无效重新洗牌 */ }
  const fresh = shuffledAll()
  try { localStorage.setItem(POOL_KEY, JSON.stringify(fresh)) } catch { /* 忽略 */ }
  return fresh
}

function savePool(pool: number[]): void {
  try { localStorage.setItem(POOL_KEY, JSON.stringify(pool)) } catch { /* 忽略 */ }
}

// 取下一条（随机）；exclude 为当前显示索引时避免原地不动（轮末除外）
export function nextPromptIndex(exclude?: number): number {
  let pool = loadPool()
  if (exclude != null && pool.length > 1) {
    pool = pool.filter((p) => p !== exclude)
  }
  if (pool.length === 0) {
    pool = shuffledAll()
  }
  const idx = pool[Math.floor(Math.random() * pool.length)]
  savePool(pool.filter((p) => p !== idx))
  return idx
}

// 上报提示显示次数（尽力而为，失败静默）——prompt_stats 表，后续按频率展示用
export function reportPromptShown(index: number): void {
  void fetch('/api/prompts/record', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ index }),
  }).catch(() => {})
}
